    def _exercise_left_merge_branch_journey(self) -> None:
        """Load -> 1.1 -> 1.2 merge -> preview -> confirm -> cache -> reopen."""
        original_fingerprint = hashlib.sha256(self.path.read_bytes()).hexdigest()
        encoded = base64.b64encode(self.workbook_bytes).decode("ascii")
        root = self.commit(self.create_root())
        class PreserveColumnsPlanner:
            def propose(self, payload: dict) -> dict:
                final_id = payload["baseRevision"]["finalOutputStepId"]
                return {
                    "summary": "Keep all Sales columns", "questions": [], "assumptions": [],
                    "warnings": [], "changeReason": "Prepare problem 1.1",
                    "changes": [
                        {"type": "insertStep", "afterStepId": final_id, "stepDraft": {
                            "clientRef": "prepared", "variableName": "PreparedSales",
                            "actionDescription": "Sort without dropping columns.",
                            "operationType": "table.sortRows",
                            "parameters": {"keys": [{"column": "SaleID", "direction": "ascending"}]},
                            "inputs": [final_id],
                        }},
                        {"type": "setFinalOutput", "stepId": "prepared"},
                    ],
                }

        self.server.app.problem_chains.planner = PreserveColumnsPlanner()
        first = self.commit(self.continue_from(root, "Prepare problem 1.1"))
        first_id = first["document"]["headRevisionId"]
        immutable_history = deepcopy(first["document"]["revisions"])
        planner = LeftMergeContinuationPlanner()
        self.server.app.problem_chains.planner = planner

        # A planning failure must not publish a candidate or move HEAD.
        class FailOnce:
            def propose(self, _payload: dict) -> dict:
                raise InputError("CODEX_TIMEOUT", "codex", "Synthetic planning deadline")

        self.server.app.problem_chains.planner = FailOnce()
        status, error = self.request("POST", "/api/pq/v2/problem-chains/problems", {
            "document": first["document"], "baseHistoryHash": first["historyHash"],
            "baseRevisionId": first_id, "creationMode": "branch",
            "prompt": "Merge Left with CommissionTable and expand Commission Rate",
            "workbook": self.workbook, "source": self.source,
        })
        self.assertEqual((status, error["error"]["code"]), (504, "CODEX_TIMEOUT"))
        self.assertEqual(self.server.app.problem_chains.active_revision(first_id)["revision"]["revisionId"], first_id)

        self.server.app.problem_chains.planner = planner
        started = time.perf_counter()
        status, candidate = self.request("POST", "/api/pq/v2/problem-chains/problems", {
            "document": first["document"], "baseHistoryHash": first["historyHash"],
            "baseRevisionId": first_id, "creationMode": "branch",
            "prompt": "Merge Left with CommissionTable and expand Commission Rate",
            "workbook": self.workbook, "source": self.source,
        })
        planning_ms = (time.perf_counter() - started) * 1000
        self.assertEqual(status, 200, candidate)
        self.assertEqual(candidate["document"]["revisions"][:-1], immutable_history)
        self.assertEqual(candidate["revision"]["parentRevisionId"], first_id)
        operations = [step["operation"]["type"] for step in candidate["revision"]["steps"]]
        self.assertLess(operations.index("table.mergeTables"), operations.index("table.expandTableColumn"))
        self.assertEqual(candidate["revision"]["validationAtCreation"]["overall"], "passed")
        head = self.commit(candidate)
        head_id = head["document"]["headRevisionId"]
        self.assertEqual(head["document"]["revisions"][:-1], immutable_history)

        started = time.perf_counter()
        status, preview = self.request("POST", "/api/pq/v2/previews", {
            "revisionId": head_id, "workbook": self.workbook, "workbookBase64": encoded,
        })
        preview_ms = (time.perf_counter() - started) * 1000
        self.assertEqual(status, 200, preview)
        self.assertFalse(self.server.app.pq_typed._problem_result_cache)
        self.assertIn("Table.NestedJoin", self.pq_runner.requests[-1]["mCode"])
        self.assertIn("Table.ExpandTableColumn", self.pq_runner.requests[-1]["mCode"])
        status, approval = self.request("POST", "/api/pq/v2/approvals", {
            "revisionId": head_id, "previewId": preview["previewId"],
            "destinationMarker": DESTINATION_MARKER,
        })
        self.assertEqual(status, 200, approval)
        status, prepared = self.request("POST", "/api/pq/v2/applies/prepare", {
            "approvalId": approval["approvalId"], "workbookBase64": encoded,
            "destination": {"marker": DESTINATION_MARKER},
        })
        self.assertEqual(status, 200, prepared)
        self.assertTrue(base64.b64decode(prepared["resultWorkbookBase64"]).startswith(b"PK"))
        status, completed = self.request("POST", "/api/pq/v2/applies/complete", {
            "applyId": prepared["applyId"], "readback": {
                "marker": DESTINATION_MARKER, "sheetName": "PQ_Typed_Result",
                "rowCount": prepared["expectedRows"], "columnCount": prepared["expectedColumns"],
            },
        })
        self.assertEqual((status, completed["status"]), (200, "applied"))
        self.assertTrue(completed["resultCached"])
        self.assertEqual(hashlib.sha256(self.path.read_bytes()).hexdigest(), original_fingerprint)

        status, reopened = self.request("POST", "/api/pq/v2/problem-chains/load", {
            "document": head["document"], "workbook": self.workbook,
        })
        self.assertEqual(status, 200, reopened)
        self.assertEqual(reopened["document"]["headRevisionId"], head_id)
        self.assertEqual(reopened["document"]["revisions"][:-1], immutable_history)
        status, checkout_old = self.request("POST", "/api/pq/v2/problem-chains/checkout", {
            "document": reopened["document"], "baseHistoryHash": reopened["historyHash"],
            "revisionId": first_id,
        })
        self.assertEqual(status, 200, checkout_old)
        old_head = self.commit(checkout_old)
        status, checkout_merge = self.request("POST", "/api/pq/v2/problem-chains/checkout", {
            "document": old_head["document"], "baseHistoryHash": old_head["historyHash"],
            "revisionId": head_id,
        })
        self.assertEqual(status, 200, checkout_merge)
        restored_head = self.commit(checkout_merge)
        runtime_calls = len(self.pq_runner.requests)
        cache_request = {
            "revisionId": head_id, "baseHistoryHash": restored_head["historyHash"],
            "sourceDataChanged": False, "workbook": self.workbook,
            "workbookBase64": encoded, "destinationMarker": DESTINATION_MARKER,
        }
        status, restored = self.request(
            "POST", "/api/pq/v2/problem-chains/cached-results/prepare", cache_request,
        )
        self.assertEqual(status, 200, restored)
        self.assertEqual(len(self.pq_runner.requests), runtime_calls, "cache restore must not rerun Excel")
        self.assertEqual((restored["expectedRows"], restored["expectedColumns"]),
                         (prepared["expectedRows"], prepared["expectedColumns"]))
        status, _ = self.request("POST", "/api/pq/v2/applies/complete", {
            "applyId": restored["applyId"], "readback": {
                "marker": DESTINATION_MARKER, "sheetName": "PQ_Typed_Result",
                "rowCount": restored["expectedRows"], "columnCount": restored["expectedColumns"],
            },
        })
        self.assertEqual(status, 200)
        changed = base64.b64encode(repack(self.workbook_bytes, change_cell=True)).decode("ascii")
        status, stale_cache = self.request("POST", "/api/pq/v2/problem-chains/cached-results/prepare", {
            **cache_request, "workbookBase64": changed,
        })
        self.assertEqual((status, stale_cache["error"]["code"]), (400, "PQPC_RESULT_CACHE_STALE"))
        print(
            f"HTTP merge journey: plan={planning_ms:.1f}ms preview={preview_ms:.1f}ms "
            f"steps={len(operations)} result={prepared['expectedRows']}x{prepared['expectedColumns']} "
            "source_sha256=unchanged"
        )

