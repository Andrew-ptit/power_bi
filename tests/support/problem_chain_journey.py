class DynamicContinuationPlanner:
    def __init__(self) -> None:
        self.calls: list[dict] = []

    def propose(self, payload: dict) -> dict:
        self.calls.append(deepcopy(payload))
        base = payload["baseRevision"]
        final_step = base["finalOutputStepId"]
        columns = base["steps"][-1]["outputContract"]["columns"]
        if "append" in payload["userRequest"].casefold():
            persisted_ids = {item["sourceId"] for item in base["sources"]}
            extra = next(item for item in payload["sourceCatalog"] if item["sourceId"] not in persisted_ids)
            return {
                "summary": "Append one explicitly referenced workbook source",
                "questions": [], "assumptions": [],
                "warnings": ["Union append may introduce nulls for columns absent from one source."],
                "changeReason": "Append an additional source",
                "changes": [
                    {
                        "type": "insertStep", "afterStepId": final_step,
                        "stepDraft": {
                            "clientRef": "extra_source", "variableName": "ExtraSource",
                            "actionDescription": "Read the explicitly referenced extra table.",
                            "operationType": "source.workbookTable",
                            "parameters": {"sourceId": extra["sourceId"]}, "inputs": [],
                        },
                    },
                    {
                        "type": "insertStep", "afterStepId": "extra_source",
                        "stepDraft": {
                            "clientRef": "appended", "variableName": "AppendedTables",
                            "actionDescription": "Append current output and the extra table.",
                            "operationType": "table.appendTables",
                            "parameters": {"schemaMode": "union"},
                            "inputs": [final_step, "extra_source"],
                        },
                    },
                    {"type": "setFinalOutput", "stepId": "appended"},
                ],
            }
        return {
            "summary": "HTTP continuation selected stable columns",
            "questions": [], "assumptions": [], "warnings": [],
            "changeReason": "HTTP continuation",
            "changes": [
                {
                    "type": "insertStep", "afterStepId": final_step,
                    "stepDraft": {
                        "clientRef": "http_selected", "variableName": "HttpSelected",
                        "actionDescription": "Select the first two available columns.",
                        "operationType": "table.selectColumns",
                        "parameters": {"columnIds": [item["columnId"] for item in columns[:2]]},
                        "inputs": [final_step],
                    },
                },
                {"type": "setFinalOutput", "stepId": "http_selected"},
            ],
        }


