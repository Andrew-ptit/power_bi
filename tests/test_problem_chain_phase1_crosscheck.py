def _independent_hash(value: object) -> str:
    """Independent canonical-hash oracle, intentionally not using product helpers."""
    raw = json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False,
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(raw).hexdigest()


def _review_basis(revision: dict) -> dict:
    return {
        "problemPrompt": revision["problemPrompt"],
        "sourceSchemaFingerprint": revision["sourceSchemaFingerprint"],
        "summary": revision["summary"],
        "questions": revision["questions"],
        "assumptions": revision["assumptions"],
        "warnings": revision["warnings"],
        "sources": revision["sources"],
        "steps": revision["steps"],
        "finalOutputStepId": revision["finalOutputStepId"],
    }


def _mutate_first_cell(payload: bytes) -> bytes:
    output = BytesIO()
    changed = False
    with zipfile.ZipFile(BytesIO(payload)) as source, zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as target:
        for item in source.infolist():
            data = source.read(item.filename)
            if not changed and item.filename.startswith("xl/worksheets/sheet") and item.filename.endswith(".xml"):
                root = ET.fromstring(data)
                value = next((node for node in root.iter(f"{{{MAIN}}}v") if node.text is not None), None)
                if value is not None:
                    value.text = "987654321" if value.text != "987654321" else "123456789"
                    data = ET.tostring(root, encoding="utf-8", xml_declaration=True)
                    changed = True
            target.writestr(item, data)
    if not changed:
        raise AssertionError("fixture contains no mutable cell value")
    return output.getvalue()


