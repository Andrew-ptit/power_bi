class BlockingContinuationPlanner:
    """Pause a continuation so a workbook load can race its publish step."""

    def __init__(self) -> None:
        self.started = threading.Event()
        self.release = threading.Event()
        self.delegate = CountingPlanner()

    def propose(self, payload: dict) -> dict:
        self.started.set()
        if not self.release.wait(timeout=2):
            raise AssertionError("blocking planner was not released")
        return self.delegate.propose(payload)


